#!/usr/bin/env node
/**
 * Generate docs/pages-index.md — inventory of every docs page under docs/.
 * Entries are plain text (backtick paths), not markdown links, so Docusaurus
 * broken-link checks stay green even when some paths are unlisted/out of tree.
 * Usage: node ./scripts/generate-docs-index.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const docsRoot = path.join(root, 'docs');
const outputPath = path.join(docsRoot, 'pages-index.md');

function walkDocs(dir, out = []) {
  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
    if (entry.name === 'pages-index.md') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walkDocs(full, out);
      continue;
    }
    if (entry.name.endsWith('.md') || entry.name.endsWith('.mdx')) out.push(full);
  }
  return out;
}

function parseFrontmatter(text) {
  if (!text.startsWith('---')) return {};
  const end = text.indexOf('\n---', 3);
  if (end === -1) return {};
  const data = {};
  for (const line of text.slice(4, end).split('\n')) {
    const match = line.match(/^([A-Za-z0-9_]+):\s*(.*)$/);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    data[match[1]] = value;
  }
  return data;
}

const files = walkDocs(docsRoot).sort();
const lines = [
  '---',
  'title: All pages index',
  'sidebar_label: All pages',
  'sidebar_position: 999',
  '---',
  '',
  '# All pages index',
  '',
  '> Auto-generated by `npm run generate:docs-index`. Do not edit by hand.',
  '>',
  '> Paths are listed as code (not links) so incomplete / unlisted docs do not fail `onBrokenLinks`.',
  '',
  `| # | Path | Title |`,
  `| --- | --- | --- |`,
];

let i = 0;
for (const full of files) {
  i += 1;
  const rel = path.relative(docsRoot, full).replace(/\\/g, '/');
  const fm = parseFrontmatter(fs.readFileSync(full, 'utf8'));
  const title = (fm.title || fm.sidebar_label || rel.replace(/\.(md|mdx)$/i, '')).replace(/\|/g, '\\|');
  lines.push(`| ${i} | \`${rel}\` | ${title} |`);
}
lines.push('');
fs.writeFileSync(outputPath, lines.join('\n'));
console.log(`Wrote ${files.length} entries to ${path.relative(root, outputPath)}`);
